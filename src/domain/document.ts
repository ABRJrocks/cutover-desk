import {
  MAX_BYTES,
  demand,
  object,
  parsePlan,
  type Document,
  type Run,
} from "./model";
import { replay } from "./run";
export function parseDocument(value: unknown): Document {
  const document = object(value, ["schemaVersion", "plan", "run"], "Document");
  demand(
    document.schemaVersion === 1,
    "Unsupported document version. Expected schemaVersion 1.",
  );
  const plan = parsePlan(document.plan);
  let run: Run | null = null;
  if (document.run !== null) {
    const raw = object(document.run, ["id", "operator", "events"], "Rehearsal");
    run = raw as unknown as Run;
    replay(plan, run);
    run = structuredClone(run);
  }
  return { schemaVersion: 1, plan, run };
}
export function decodeDocument(raw: string): Document {
  demand(
    new TextEncoder().encode(raw).length <= MAX_BYTES,
    "Document exceeds the two MiB import limit.",
  );
  let value: unknown;
  try {
    value = JSON.parse(raw);
  } catch {
    throw new Error("The file is not valid JSON.");
  }
  return parseDocument(value);
}
export function encodeDocument(document: Document): string {
  const raw = JSON.stringify(parseDocument(document), null, 2);
  demand(
    new TextEncoder().encode(raw).length <= MAX_BYTES,
    "Document exceeds the two MiB limit. Export the current rehearsal before starting another.",
  );
  return raw;
}
export function markdown(document: Document): string {
  const escape = (text: string) =>
    text.replace(/[\\`*_[\]<>|#]/g, "\\$&").replace(/\r?\n/g, " ");
  const p = document.plan;
  const lines = [
    `# ${escape(p.title)}`,
    "",
    escape(p.summary),
    "",
    `Change window: ${p.windowMinutes} minutes.`,
    "",
    "## Plan",
    "",
  ];
  for (const step of p.steps)
    lines.push(
      `### ${escape(step.title)} (${step.id})`,
      "",
      `Owner: ${escape(step.owner)} | Estimate: ${step.minutes} minutes | Type: ${step.kind}`,
      `Depends on: ${step.dependsOn.join(", ") || "none"}`,
      "",
      `Instructions: ${escape(step.instructions)}`,
      "",
      `Verify: ${escape(step.verification)}`,
      "",
      `Rollback review: ${escape(step.rollback)}`,
      "",
    );
  if (document.run) {
    const view = replay(p, document.run);
    lines.push(
      "## Rehearsal record",
      "",
      `Coordinator: ${escape(document.run.operator)}`,
      `Outcome: ${view.phase}`,
      `Rehearsal ID: ${document.run.id}`,
      "",
      "Human-reported observations. This record is editable and is not a verified approval or production check.",
      "",
    );
    for (const event of document.run.events)
      lines.push(
        `- ${new Date(event.at).toISOString()} | ${event.type}${event.stepId ? " | " + event.stepId : ""}${event.note ? " | " + escape(event.note) : ""}`,
      );
  }
  lines.push(
    "",
    "Generated by Cutover Desk. Local planning and rehearsal only; no production commands were executed.",
    "",
  );
  return lines.join("\n");
}
